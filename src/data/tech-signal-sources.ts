/**
 * Tech Signal Stack: fonte única de verdade da curadoria.
 *
 * Vive aqui (e não dentro da página) para passar pelo `astro check`, para poder
 * ser reaproveitada por outras rotas e para que a página consiga renderizar os
 * cards no servidor, sem depender de JavaScript no cliente.
 *
 * tier 1 = leitura recorrente inegociável
 * tier 2 = excelente, o peso depende do seu papel
 * tier 3 = consulta pontual, quando o assunto aparece
 */

export type SignalTier = 1 | 2 | 3;

export type SignalCategoryId =
	| 'brasil'
	| 'geral'
	| 'ia'
	| 'dev'
	| 'negocios'
	| 'politica'
	| 'seguranca'
	| 'educacao'
	| 'newsletter';

/**
 * O que a fonte faz, que é diferente do assunto sobre o qual ela fala.
 * Sem essa distinção, um agregador comunitário, o blog de um laboratório
 * e uma redação com apuração própria ficam com a mesma aparência de card.
 */
export type SignalKind =
	| 'jornalismo'
	| 'analise'
	| 'pesquisa'
	| 'primaria'
	| 'descoberta';

export type SignalAccess = 'aberto' | 'assinatura';
export type SignalCadence = 'Diária' | 'Semanal' | 'Mensal' | 'Anual';
export type SignalRegion = 'Brasil' | 'LATAM' | 'Global';

export interface SignalSource {
	name: string;
	url: string;
	tier: SignalTier;
	kind: SignalKind;
	cats: SignalCategoryId[];
	desc: string;
	cadence: SignalCadence;
	access: SignalAccess;
	region: SignalRegion;
	/**
	 * Feed RSS ou Atom, verificado por requisição real antes de entrar aqui:
	 * tem que responder 200, devolver XML de feed e trazer itens de conteúdo.
	 * Ausente quando a fonte não publica feed utilizável. Reuters e Anthropic
	 * não expõem RSS público, o Banco Central serve JSON, o único feed do Daily
	 * Papers é espelho de terceiro, e os feeds do gov.br são listagem de pasta
	 * do Plone, com metade dos itens sendo arquivo de imagem solto. Os órgãos
	 * seguem na curadoria como fonte primária, que se consulta em vez de
	 * assinar. Alimenta /tech-signal.opml.
	 */
	feed?: string;
	/** Marca as fontes que recompensam leitura longa, não escaneio. */
	deep?: boolean;
	topics: string[];
}

export interface SignalCategory {
	id: SignalCategoryId | 'todas';
	label: string;
}

